"""Build a static, shareable HTML site from saved run records."""

from __future__ import annotations

import html

from safeagenteval.reporting.report import build_leaderboard


def render_site_html(
    records: list[dict[str, object]], *, title: str = "SafeAgentEval results"
) -> str:
    """Render an index page summarizing run records (no external assets)."""
    board = build_leaderboard(records)
    rows: list[str] = []
    for record in records:
        score = record.get("state_score")
        score = score if isinstance(score, dict) else {}
        rows.append(
            "<tr>"
            f"<td>{html.escape(str(record.get('scenario_id')))}</td>"
            f"<td>{html.escape(str(record.get('configuration')))}</td>"
            f"<td>{html.escape(str(record.get('passed')))}</td>"
            f"<td>{html.escape(str(score.get('final_state_correct')))}</td>"
            f"<td>{html.escape(str(score.get('unauthorized_action')))}</td>"
            f"<td>{html.escape(str(score.get('successful_commits')))}</td>"
            "</tr>"
        )
    body = "\n".join(rows)
    return (
        "<!DOCTYPE html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">"
        f"<title>{html.escape(title)}</title>"
        "<style>body{font-family:system-ui,sans-serif;margin:2rem}"
        "table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:4px 8px}"
        "</style></head><body>"
        f"<h1>{html.escape(title)}</h1>"
        f"<p>Runs: {board['runs']} &middot; Passed: {board['passed']} &middot; "
        f"Pass rate: {board['pass_rate']} &middot; "
        f"Unauthorized runs: {board['unauthorized_runs']}</p>"
        "<table><thead><tr><th>Scenario</th><th>Configuration</th><th>Passed</th>"
        "<th>Final state</th><th>Unauthorized</th><th>Commits</th></tr></thead>"
        f"<tbody>{body}</tbody></table>"
        "<p>Generated by SafeAgentEval. A passed run means: completed, authorized "
        "final state, no unauthorized action, trace verified.</p>"
        "</body></html>\n"
    )
