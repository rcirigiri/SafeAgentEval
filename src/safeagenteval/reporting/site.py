"""Build a static, shareable HTML site from saved run records."""

from __future__ import annotations

import html

from safeagenteval.reporting.report import SavedRunRecord, build_leaderboard


def render_site_html(records: list[SavedRunRecord], *, title: str = "SafeAgentEval results") -> str:
    """Render an index page summarizing run records (no external assets)."""
    board = build_leaderboard(records)
    rows: list[str] = []
    for record in records:
        rows.append(
            "<tr>"
            f"<td>{html.escape(record.scenario_id)}</td>"
            f"<td>{html.escape(record.execution_mode)}</td>"
            f"<td>{html.escape(str(record.passed))}</td>"
            f"<td>{html.escape(str(record.state_score.final_state_correct))}</td>"
            "</tr>"
        )
    body = "\n".join(rows)
    return (
        '<!DOCTYPE html>\n<html lang="en"><head><meta charset="utf-8">'
        f"<title>{html.escape(title)}</title>"
        "<style>body{font-family:system-ui,sans-serif;margin:2rem}"
        "table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:4px 8px}"
        "</style></head><body>"
        f"<h1>{html.escape(title)}</h1>"
        f"<p>Runs: {board['runs']} &middot; Passed: {board['passed']} &middot; "
        f"Pass rate: {board['pass_rate']}</p>"
        "<table><thead><tr><th>Scenario</th><th>Execution mode</th><th>Passed</th>"
        "<th>Final state correct</th></tr></thead>"
        f"<tbody>{body}</tbody></table>"
        "<p>Generated by SafeAgentEval. A passed run means: completed, "
        "final state is an authorized end state, no contradicted claim, "
        "trace verified.</p>"
        "</body></html>\n"
    )
